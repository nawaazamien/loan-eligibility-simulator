import mswPackage from '../../node_modules/msw/package.json?raw';
import worker from '../../public/mockServiceWorker.js?raw';

describe('the committed service worker script', () => {
  it('was generated by the installed version of msw', () => {
    const installed = (JSON.parse(mswPackage) as { version: string }).version;
    const generatedBy = /const PACKAGE_VERSION = '([^']+)'/.exec(worker)?.[1];
    // After upgrading msw, regenerate it with `npx msw init public --no-save` (docs/API.md).
    expect(generatedBy).toBe(installed);
  });

  it('is the unmodified file msw generates', () => {
    expect(worker).toContain('Please do NOT modify this file');
    expect(worker).toMatch(/const INTEGRITY_CHECKSUM = '[0-9a-f]{32}'/);
  });
});
